/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_SPI1_Init();
  MX_TIM3_Init();
  MX_USB_DEVICE_Init();
  MX_SPI2_Init();
  MX_SPI3_Init();
  /* USER CODE BEGIN 2 */
  // Start the backlight PWM on TIM3 CH3
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_3);
  __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, 32767); // 50% brightness

  // Initialize the Display and Touch
  ILI9488_Init();
  XPT2046_Init();

  // Draw Tally Counter UI
  ILI9488_FillScreen(ILI9488_BLACK);

  // Title
  ILI9488_WriteStringScaled(90, 20, "TALLY COUNTER", Font_7x10, ILI9488_WHITE,
                            ILI9488_BLACK, 3);

  // Minus Button [-] (Red)
  ILI9488_FillRectangle(20, 110, 100, 100, ILI9488_RED);
  ILI9488_WriteCharScaled(20 + 40, 110 + 35, '-', Font_7x10, ILI9488_WHITE,
                          ILI9488_RED, 5);

  // Plus Button [+] (Green)
  ILI9488_FillRectangle(360, 110, 100, 100, ILI9488_GREEN);
  ILI9488_WriteCharScaled(360 + 35, 110 + 35, '+', Font_7x10, ILI9488_WHITE,
                          ILI9488_GREEN, 5);

  int counter = 0;
  char buf[16];
  sprintf(buf, "%04d", counter);

  // Initial Counter Value
  ILI9488_WriteStringScaled(180, 130, buf, Font_7x10, ILI9488_YELLOW,
                            ILI9488_BLACK, 5);

  uint16_t touch_x = 0, touch_y = 0;
  uint8_t touched = 0;

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1) {
    if (XPT2046_GetTouch(&touch_x, &touch_y)) {
      if (!touched) {
        touched = 1;

        // Check if Minus Button [-] is pressed
        if (touch_x >= 20 && touch_x <= 120 && touch_y >= 110 &&
            touch_y <= 210) {
          if (counter > 0)
            counter--;
          sprintf(buf, "%04d", counter);
          ILI9488_WriteStringScaled(180, 130, buf, Font_7x10, ILI9488_YELLOW,
                                    ILI9488_BLACK, 5);
        }

        // Check if Plus Button [+] is pressed
        if (touch_x >= 360 && touch_x <= 460 && touch_y >= 110 &&
            touch_y <= 210) {
          if (counter < 9999)
            counter++;
          sprintf(buf, "%04d", counter);
          ILI9488_WriteStringScaled(180, 130, buf, Font_7x10, ILI9488_YELLOW,
                                    ILI9488_BLACK, 5);
        }

        // Debounce delay to avoid multiple registrations on single touch
        HAL_Delay(200);
      }

      // DEBUG: Draw the coordinates on the screen so we know what XPT2046 is
      // reading
      char dbg_buf[32];
      sprintf(dbg_buf, "X:%04d Y:%04d", touch_x, touch_y);
      ILI9488_WriteStringScaled(120, 220, dbg_buf, Font_7x10, ILI9488_WHITE,
                                ILI9488_BLACK, 2);

    } else {
      touched = 0;
    }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

